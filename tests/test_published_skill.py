"""The published skill and the package constant must stay byte-identical.

Three copies exist and they serve different readers:

* `src/codegraph/commands/skills.py` — the constant `install-skills` writes
* `.dsh/skills/codegraph-why/SKILL.md` — the DSH project root, committed
* `skills/codegraph-why/SKILL.md` — the conventional path `npx skills` and the
  marketplaces scan

Only the first can be regenerated by a command, so the other two have to be checked
against it. A stale published copy is worse than a missing one: an agent would follow
instructions the package no longer ships.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from codegraph.commands.skills import SKILL_FILE, SKILL_NAME

ROOT = Path(__file__).resolve().parent.parent

COPIES = [
    ROOT / ".dsh" / "skills" / SKILL_NAME / "SKILL.md",
    ROOT / "skills" / SKILL_NAME / "SKILL.md",
]


@pytest.mark.parametrize("path", COPIES, ids=lambda p: str(p.relative_to(ROOT)))
def test_committed_skill_matches_the_package_constant(path: Path) -> None:
    """Every committed copy must equal what `install-skills` would write."""
    assert path.is_file(), f"{path} is missing"
    assert path.read_text(encoding="utf-8") == SKILL_FILE, (
        f"{path.relative_to(ROOT)} has drifted from the package constant.\n"
        f"Regenerate with:\n"
        f"  codegraph install-skills --target project --force\n"
        f"  codegraph install-skills --target published --force"
    )


def test_published_skill_has_the_frontmatter_agents_require() -> None:
    """A marketplace listing reads `name` and `description` from the frontmatter."""
    published = ROOT / "skills" / SKILL_NAME / "SKILL.md"
    text = published.read_text(encoding="utf-8")

    assert text.startswith("---\n"), "frontmatter must be the first thing in the file"
    _, frontmatter, _body = text.split("---", 2)
    assert f"name: {SKILL_NAME}" in frontmatter
    assert "description:" in frontmatter

    # The name field is what a user types; it must match the directory.
    assert published.parent.name == SKILL_NAME


def test_published_skill_lists_the_install_command() -> None:
    """A reader who lands on the skill folder needs the install step, not just the promise."""
    text = (ROOT / "skills" / SKILL_NAME / "SKILL.md").read_text(encoding="utf-8")
    assert "pip install codegraphx" in text
    assert "codegraph index" in text
    assert "codegraph why" in text


def test_published_skill_states_the_honest_empty_case() -> None:
    """The property that distinguishes this tool from a plausible-sounding guess."""
    text = (ROOT / "skills" / SKILL_NAME / "SKILL.md").read_text(encoding="utf-8")
    assert "found: false" in text
    assert "real answer" in text
